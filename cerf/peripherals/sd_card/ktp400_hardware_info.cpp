#include "ktp400_hardware_info.h"

#include <iterator>

namespace {

constexpr char kHex[] = "0123456789ABCDEF";

}  // namespace

std::vector<uint8_t> BuildKtp400HardwareInfoOms(
    const std::array<uint8_t, 6>& mac) {
    /* The base object is the MicroOMS hardware-info tree extracted from the
       Siemens KTP400 V13 FWF.  The final root-object A2 is appended below.

       IDA bspio.dll HWI_GetMACAddressInfo 0x418851DC walks object 0x474C,
       child 0x4928 and string property 0x492B.  Its parser at 0x41884930
       requires exactly 17 characters and accepts ':' separators.  The FWF
       MicroOMS stream encodes an object as A1/header/id/00/00 ... A2 and an
       ASCII string property as A3/id/00/15/length/payload. */
    static constexpr uint8_t kBaseOmsRoot[] = {
        0x03,
        0xA1, 0x00,0x00,0x00,0x00, 0x00,0x00,0x00,
          0xA1, 0x00,0x00,0x00,0x00, 0x81,0x8E,0x3F, 0x00,0x00,
            0xA1, 0x00,0x00,0x00,0x00, 0x81,0x8E,0x58, 0x00,0x00,
              0xA3, 0x81,0x8E,0x59, 0x00,0x04, 0x83,0x60,
              0xA3, 0x81,0x8E,0x5A, 0x00,0x04, 0x82,0x10,
              0xA3, 0x81,0x8E,0x5B, 0x00,0x04, 0x80,0x5F,
              0xA3, 0x81,0x8E,0x5C, 0x00,0x04, 0x80,0x36,
              0xA3, 0x81,0x92,0x44, 0x00,0x04, 0x01,
              0xA3, 0x81,0x92,0x45, 0x00,0x04, 0x0F,
              0xA3, 0x81,0x92,0x46, 0x00,0x04, 0x80,0x64,
              0xA3, 0x81,0x92,0x47, 0x00,0x04, 0x00,
              0xA3, 0x81,0x92,0x48, 0x00,0x04, 0x80,0x64,
            0xA2,
            0xA1, 0x00,0x00,0x00,0x00, 0x81,0x8E,0x5E, 0x00,0x00, 0xA2,
            0xA1, 0x00,0x00,0x00,0x00, 0x81,0x8E,0x63, 0x00,0x00, 0xA2,
          0xA2,
          0xA1, 0x00,0x00,0x00,0x00, 0x81,0x92,0x07, 0x00,0x00,
            0xA3, 0x81,0x92,0x0A, 0x00,0x04, 0x40,
            0xA3, 0x81,0x92,0x0D, 0x00,0x04, 0x01,
          0xA2
    };
    static constexpr uint8_t kMacObjectPrefix[] = {
        0xA1, 0x00,0x00,0x00,0x00, 0x81,0x8E,0x4C, 0x00,0x00,
          0xA1, 0x00,0x00,0x00,0x00, 0x81,0x92,0x28, 0x00,0x00,
            0xA3, 0x81,0x92,0x2B, 0x00,0x15, 0x11
    };

    std::vector<uint8_t> oms(std::begin(kBaseOmsRoot), std::end(kBaseOmsRoot));
    oms.insert(oms.end(), std::begin(kMacObjectPrefix), std::end(kMacObjectPrefix));
    for (std::size_t i = 0; i < mac.size(); ++i) {
        if (i != 0u)
            oms.push_back(':');
        oms.push_back(static_cast<uint8_t>(kHex[mac[i] >> 4u]));
        oms.push_back(static_cast<uint8_t>(kHex[mac[i] & 0x0Fu]));
    }
    oms.push_back(0xA2);  // 0x4928
    oms.push_back(0xA2);  // 0x474C
    oms.push_back(0xA2);  // root
    return oms;
}
